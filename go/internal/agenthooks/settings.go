func buildClaudeSettings(specs []HookSpec, hookCommand string) claudeSettings {
	hooks := make(map[string][]matcherHook)
	for _, spec := range specs {
		hooks[spec.Event] = append(
			hooks[spec.Event],
			commandMatcher(spec.Tool, hookCommand),
		)
	}

	addNoopProviderMatchers(
		hooks,
		toolaliases.ProviderClaude,
		hookCommand,
		commandMatcher,
	)

	return claudeSettings{Hooks: hooks}
}

func buildCodexSettings(specs []HookSpec, hookCommand string) claudeSettings {
	hooks := make(map[string][]matcherHook)

	for _, spec := range specs {
		for _, matcher := range codexHookMatchers(spec) {
			hooks[spec.Event] = append(
				hooks[spec.Event],
				codexMatcher(matcher, hookCommand),
			)
		}
	}

	addNoopProviderMatchers(hooks, toolaliases.ProviderCodex, hookCommand, codexMatcher)

	return claudeSettings{Hooks: hooks}
}

func codexHookMatchers(spec HookSpec) []string {
	if spec.Event == eventSessionStart || spec.Event == eventUserPromptSubmit {
		return []string{""}
	}

	if spec.Event == eventStop {
		return []string{""}
	}

	if !codexToolEvent(spec.Event) || !codexSupportsTool(spec.Tool) {
		return nil
	}

	return []string{codexMatcherFor(spec.Tool)}
}

func codexToolEvent(event string) bool {
	return event == eventPreToolUse || event == eventPostToolUse
}

func codexSupportsTool(tool string) bool {
	return tool == toolaliases.CanonicalShell || toolaliases.IsWriteLike(tool)
}

func buildGeminiSettings(specs []HookSpec, hookCommand string) claudeSettings {
	hooks := make(map[string][]matcherHook)

	for _, spec := range specs {
		event, matcher, found := geminiHookSpec(spec)
		if !found {
			continue
		}

		hooks[event] = append(
			hooks[event],
			geminiMatcher(matcher, hookCommand),
		)
	}

	addNoopProviderMatchers(
		hooks,
		toolaliases.ProviderGemini,
		hookCommand,
		geminiMatcher,
	)

	return claudeSettings{
		Hooks:       hooks,
		HooksConfig: map[string]any{"enabled": true},
	}
}

func addNoopProviderMatchers(
	hooks map[string][]matcherHook,
	provider string,
	hookCommand string,
	build func(string, string) matcherHook,
) {
	aliases := toolaliases.ProviderAliases(provider, toolaliases.CanonicalNoop)
	for _, alias := range aliases {
		preEvent, postEvent := providerToolEvents(provider)
		hooks[preEvent] = append(
			hooks[preEvent],
			build(providerMatcher(alias), hookCommand),
		)
		hooks[postEvent] = append(
			hooks[postEvent],
			build(providerMatcher(alias), hookCommand),
		)
	}
}

func providerToolEvents(provider string) (string, string) {
	if provider == toolaliases.ProviderGemini {
		return eventBeforeTool, eventAfterTool
	}

	return eventPreToolUse, eventPostToolUse
}

func codexMatcherFor(canonical string) string {
	aliases := toolaliases.ProviderAliases(toolaliases.ProviderCodex, canonical)

	parts := make([]string, 0, len(aliases))
	for _, alias := range aliases {
		parts = append(parts, providerMatcher(alias))
	}

	return strings.Join(parts, "|")
}

func providerMatcher(alias toolaliases.Alias) string {
	if alias.Regex {
		return regexp.QuoteMeta(alias.Name)
	}

	return alias.Name
}

