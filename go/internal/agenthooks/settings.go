// VerifySettingsForRepositoryWithMCPCommand validates split supervisor-hook
// and Coding Ethos MCP ownership, then runs provider probes through the hook.
func VerifySettingsForRepositoryWithMCPCommand(
	settingsRoot string,
	repoRoot string,
	hookCommand string,
	mcpCommand string,
) (VerifyReport, error) {
	err := DoctorSettingsForRepositoryWithMCPCommand(
		settingsRoot,
		repoRoot,
		hookCommand,
		mcpCommand,
	)
	if err != nil {
		return VerifyReport{
			Status:       verifyStatusInvalid,
			Capabilities: ProviderCapabilities(),
			Checks: []VerifyCheck{{
				Provider: "all",
				Event:    "settings",
				Status:   verifyStatusFail,
				Detail:   err.Error(),
			}},
		}, err
	}

	report := VerifyReport{
		Status:       verifyStatusValid,
		Capabilities: ProviderCapabilities(),
	}

	err = appendSkillSurfaceChecks(repoRoot, &report)
	if err != nil {
		return report, err
	}

	for _, probe := range hookProbes() {
		result, err := runHookProbe(repoRoot, hookCommand, probe)

		check := VerifyCheck{
			Provider: probe.provider,
			Event:    probe.event,
			Tool:     probe.tool,
			Status:   verifyStatusPass,
		}
		if err != nil {
			check.Status = verifyStatusFail
			check.Detail = err.Error()
			report.Status = verifyStatusInvalid
			report.Checks = append(report.Checks, check)

			return report, err
		}

		err = probe.validate(result)
		if err != nil {
			check.Status = verifyStatusFail
			check.Detail = err.Error()
			report.Status = verifyStatusInvalid
			report.Checks = append(report.Checks, check)

			return report, err
		}

		report.Checks = append(report.Checks, check)
	}

	return report, nil
}

func appendSkillSurfaceChecks(root string, report *VerifyReport) error {
	checks, err := verifySkillSurfaces(root)

	report.Checks = append(report.Checks, checks...)
	if err != nil {
		report.Status = verifyStatusInvalid

		return err
	}

	return nil
}

func verifySkillSurfaces(root string) ([]VerifyCheck, error) {
	skillIDs, err := repoSkillIDs(root)
	if err != nil {
		return nil, err
	}

	if len(skillIDs) == 0 {
		return nil, nil
	}

	checks := make([]VerifyCheck, 0, len(skillIDs)*skillSurfaceCount)

	var verifyErr error

	for _, skillID := range skillIDs {
		for _, surface := range skillSurfacePaths(root, skillID) {
			check := VerifyCheck{
				Provider: surface.provider,
				Event:    "skill-surface",
				Tool:     skillID,
				Status:   verifyStatusPass,
			}

			err := verifySkillFile(surface.path, skillID)
			if err != nil {
				check.Status = verifyStatusFail
				check.Detail = err.Error()
				verifyErr = errors.Join(verifyErr, err)
			}

			checks = append(checks, check)
		}
	}

	return checks, verifyErr
}

const skillSurfaceCount = 4

type skillSurfacePath struct {
	provider string
	path     string
}

func repoSkillIDs(root string) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(root, ".agents", "skills"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}

	if err != nil {
		return nil, fmt.Errorf("read generated skill directory: %w", err)
	}

	skillIDs := []string{}

	for _, entry := range entries {
		if entry.IsDir() {
			skillIDs = append(skillIDs, entry.Name())
		}
	}

	slices.Sort(skillIDs)

	return skillIDs, nil
}

func skillSurfacePaths(root, skillID string) []skillSurfacePath {
	entrypoint := filepath.Join(skillID, "SKILL.md")

	return []skillSurfacePath{
		{
			provider: string(ProviderGeneric),
			path:     filepath.Join(root, ".agents", "skills", entrypoint),
		},
		{
			provider: string(ProviderClaude),
			path:     filepath.Join(root, ".claude", "skills", entrypoint),
		},
		{
			provider: string(ProviderCodex),
			path:     filepath.Join(root, ".codex", "skills", entrypoint),
		},
		{
			provider: string(ProviderGemini),
			path: filepath.Join(
				root,
				".gemini",
				"extensions",
				"coding-ethos",
				"skills",
				entrypoint,
			),
		},
	}
}

func verifySkillFile(path, skillID string) error {
	content, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return fmt.Errorf("read generated skill %s: %w", path, err)
	}

	frontmatter, err := parseSkillFrontmatter(string(content))
	if err != nil {
		return fmt.Errorf("read generated skill metadata %s: %w", path, err)
	}

	if frontmatter.Name != skillID ||
		frontmatter.EffectiveSource() != "coding_ethos.yml" {
		return apperror.Wrapf(
			apperror.StaticError("generated skill %s does not match skill %s"),
			"generated skill %s does not match skill %s",
			path,
			skillID,
		)
	}

	return nil
}

type skillFrontmatter struct {
	Metadata struct {
		Source string `yaml:"source"`
	} `yaml:"metadata"`
	Name   string `yaml:"name"`
	Source string `yaml:"source"`
}

func (frontmatter skillFrontmatter) EffectiveSource() string {
	if frontmatter.Metadata.Source != "" {
		return frontmatter.Metadata.Source
	}

	return frontmatter.Source
}

func parseSkillFrontmatter(content string) (skillFrontmatter, error) {
	if !strings.HasPrefix(content, "---\n") {
		return skillFrontmatter{}, errMissingSkillFrontmatter
	}

	remainder := strings.TrimPrefix(content, "---\n")

	raw, _, found := strings.Cut(remainder, "\n---")
	if !found {
		return skillFrontmatter{}, errMissingSkillFrontmatter
	}

	var frontmatter skillFrontmatter

	err := yaml.Unmarshal([]byte(raw), &frontmatter)
	if err != nil {
		return skillFrontmatter{}, fmt.Errorf("parse YAML frontmatter: %w", err)
	}

	return frontmatter, nil
}

