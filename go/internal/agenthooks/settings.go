func geminiHookSpec(spec HookSpec) (string, string, bool) {
	if spec.Event == eventSessionStart {
		return eventSessionStart, "startup", true
	}

	if spec.Event == eventUserPromptSubmit {
		return "BeforeAgent", "prompt", true
	}

	if spec.Event == eventStop {
		return "AfterAgent", "stop", true
	}

	if spec.Event == "SessionEnd" {
		return "SessionEnd", "session", true
	}

	event, found := geminiToolEvent(spec.Event)
	if !found || !geminiSupportsTool(spec.Tool) {
		return "", "", false
	}

	return event, firstGeminiAlias(spec.Tool), true
}

func geminiToolEvent(event string) (string, bool) {
	switch event {
	case eventPreToolUse:
		return eventBeforeTool, true
	case eventPostToolUse:
		return eventAfterTool, true
	default:
		return "", false
	}
}

func geminiSupportsTool(tool string) bool {
	return tool == toolaliases.CanonicalShell || toolaliases.IsWriteLike(tool)
}

func firstGeminiAlias(canonical string) string {
	aliases := toolaliases.ProviderAliases(toolaliases.ProviderGemini, canonical)
	if len(aliases) == 0 {
		return canonical
	}

	return aliases[0].Name
}

func codexHookFeatureEnabled(content string) bool {
	inFeatures := false

	for line := range strings.SplitSeq(content, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") && strings.HasSuffix(trimmed, "]") {
			inFeatures = trimmed == "[features]"

			continue
		}

		if inFeatures && isCodexHookFlag(trimmed) {
			return strings.Contains(trimmed, "true")
		}
	}

	return false
}

func settingsContainExpectedHooks(
	actual claudeSettings,
	expected claudeSettings,
) bool {
	for event, expectedMatchers := range expected.Hooks {
		actualMatchers := actual.Hooks[event]
		for _, expectedMatcher := range expectedMatchers {
			if !containsMatcher(actualMatchers, expectedMatcher) {
				return false
			}
		}
	}

	return true
}

func containsMatcher(actual []matcherHook, expected matcherHook) bool {
	for _, candidate := range actual {
		if candidate.Matcher != expected.Matcher {
			continue
		}

		if containsCommandHook(candidate.Hooks, expected.Hooks[0]) {
			return true
		}
	}

	return false
}

func containsCommandHook(actual []commandHook, expected commandHook) bool {
	return slices.Contains(actual, expected)
}
