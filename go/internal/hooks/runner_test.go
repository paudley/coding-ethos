func codexApplyPatchLargeGoEvent(t *testing.T, repo string) Event {
	t.Helper()

	file := filepath.Join(repo, "go", "cmd", "coding-ethos-hook-runner", "main.go")

	inlineErr0 := os.MkdirAll(filepath.Dir(file), 0o700)
	if inlineErr0 != nil {
		t.Fatalf("create source dir: %v", inlineErr0)
	}

	inlineErr1 := os.WriteFile(file, []byte(strings.Repeat("line\n", 2001)), 0o600)
	if inlineErr1 != nil {
		t.Fatalf("write source file: %v", inlineErr1)
	}

	event, err := DecodeEvent(strings.NewReader(codexApplyPatchEventJSON(repo)))
	if err != nil {
		t.Fatalf("decode event: %v", err)
	}

	return event
}

func codexApplyPatchEventJSON(repo string) string {
	patchCommand := strings.Join([]string{
		"*** Begin Patch",
		"*** Update File: go/cmd/coding-ethos-hook-runner/main.go",
		"@@",
		"+newLine",
		"*** End Patch",
		"",
	}, "\n")

	return `{
		"provider": "codex",
		"event": "PreToolUse",
		"tool": "functions.apply_patch",
		"cwd": ` + strconv.Quote(repo) + `,
		"input": {
			"cmd": ` + strconv.Quote(patchCommand) + `
		}
	}`
}

